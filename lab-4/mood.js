let mood = "happy";

switch (mood) {

    case "happy":
        console.log("😊 You are happy!");
        break;

    case "sad":
        console.log("😢 Don't worry, everything will be okay.");
        break;

    case "angry":
        console.log("😠 Stay calm.");
        break;

    case "tired":
        console.log("😴 Take some rest.");
        break;

    default:
        console.log("Have a nice day!");
}